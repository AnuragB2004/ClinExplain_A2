import streamlit as st
import pandas as pd
import matplotlib.pyplot as plt
from datetime import datetime, timezone
import json, os

st.set_page_config(page_title="ClinExplain | Research Prototype", page_icon="🩺", layout="wide")

st.title("ClinExplain")
st.caption("Research prototype: comparing static feature attribution with interactive counterfactual explanations")
st.warning("Academic simulation only. Uses synthetic cases and illustrative rules, not a validated clinical model. Do not use for diagnosis or patient care.")

CASES = {
    "Case A — routine review": {
        "age": 54, "symptom_duration_days": 3, "temperature_c": 37.4,
        "heart_rate": 92, "oxygen_saturation": 97, "risk_factor": "None recorded",
        "reference_label": "Lower concern in this illustrative scenario",
        "model_label": "Lower concern", "confidence": 0.78,
        "features": {"Symptom duration": 0.28, "Heart rate": 0.24, "Temperature": 0.19, "Oxygen saturation": 0.17, "Age": 0.12},
        "counterfactual": "In this illustrative rule set, a sustained increase in heart rate or a drop in oxygen saturation would move the case into the higher-concern category.",
        "note": "The displayed score and explanation are synthetic teaching values."
    },
    "Case B — deliberately misleading AI recommendation": {
        "age": 71, "symptom_duration_days": 1, "temperature_c": 38.1,
        "heart_rate": 118, "oxygen_saturation": 91, "risk_factor": "Chronic respiratory condition",
        "reference_label": "Higher concern in this illustrative scenario",
        "model_label": "Lower concern", "confidence": 0.86,
        "features": {"Symptom duration": 0.10, "Heart rate": 0.25, "Temperature": 0.18, "Oxygen saturation": 0.32, "Age": 0.15},
        "counterfactual": "The deliberately flawed recommendation is not reliable. The scenario is designed to prompt the user to inspect the low oxygen saturation, elevated heart rate and age rather than accept the AI output.",
        "note": "This scenario intentionally contains an incorrect recommendation to support discussion of automation bias."
    },
    "Case C — borderline case": {
        "age": 46, "symptom_duration_days": 5, "temperature_c": 37.8,
        "heart_rate": 101, "oxygen_saturation": 95, "risk_factor": "Not specified",
        "reference_label": "Requires further review in this illustrative scenario",
        "model_label": "Higher concern", "confidence": 0.61,
        "features": {"Symptom duration": 0.20, "Heart rate": 0.30, "Temperature": 0.18, "Oxygen saturation": 0.22, "Age": 0.10},
        "counterfactual": "Small changes in the illustrative inputs could change the category. The case is intended to demonstrate uncertainty and the need for verification.",
        "note": "The values are fabricated and are not clinical thresholds."
    }
}

if "events" not in st.session_state:
    st.session_state.events = []

with st.sidebar:
    st.header("Scenario")
    case_name = st.selectbox("Select synthetic case", list(CASES.keys()))
    st.markdown("---")
    st.markdown("**Study condition**")
    explanation_mode = st.radio("Explanation modality", ["Static feature attribution", "Interactive counterfactual"])
    st.caption("Switching the modality changes the explanation shown, not the underlying synthetic case.")

case = CASES[case_name]
left, right = st.columns([1, 1])
with left:
    st.subheader("1. Patient vignette")
    st.metric("Age (synthetic)", f"{case['age']} years")
    st.write(f"**Symptom duration:** {case['symptom_duration_days']} days")
    st.write(f"**Temperature:** {case['temperature_c']} °C")
    st.write(f"**Heart rate:** {case['heart_rate']} bpm")
    st.write(f"**Oxygen saturation:** {case['oxygen_saturation']}%")
    st.write(f"**Relevant history:** {case['risk_factor']}")
with right:
    st.subheader("2. AI recommendation")
    st.metric("Illustrative recommendation", case["model_label"], delta=f"{case['confidence']:.0%} displayed confidence", delta_color="off", delta_arrow="off")
    st.write(f"**Scenario reference:** {case['reference_label']}")
    st.info(case["note"])

st.divider()
st.subheader("3. Explanation")
if explanation_mode == "Static feature attribution":
    st.write("The bars represent illustrative feature contributions. They are not generated by SHAP or a trained model.")
    fig, ax = plt.subplots(figsize=(7, 3.1))
    names = list(case["features"].keys())
    vals = list(case["features"].values())
    ax.barh(names[::-1], vals[::-1])
    ax.set_xlabel("Illustrative contribution (not a clinical measure)")
    ax.set_xlim(0, max(vals) * 1.2)
    fig.tight_layout()
    st.pyplot(fig, width="stretch")
    st.caption("Design intent: make influential inputs visible. A feature attribution display can still make an incorrect recommendation appear persuasive.")
else:
    st.write("Inspect the hypothetical changes below. The values are explanatory prompts, not validated clinical thresholds.")
    st.info(case["counterfactual"])
    st.markdown("**Interactive what-if controls**")
    st.caption("Change the illustrative values to inspect how the case description changes. These controls do not calculate a diagnosis or apply clinical thresholds.")
    whatif_hr = st.slider("What-if heart rate (bpm)", 50, 160, int(case["heart_rate"]), key=f"hr_{case_name}")
    whatif_o2 = st.slider("What-if oxygen saturation (%)", 80, 100, int(case["oxygen_saturation"]), key=f"o2_{case_name}")
    st.write(f"Compared with the starting vignette: heart rate {whatif_hr - case['heart_rate']:+d} bpm; oxygen saturation {whatif_o2 - case['oxygen_saturation']:+d} percentage points.")
    st.markdown("**Verification prompt**")
    st.write("1. Which input most concerns you?")
    st.write("2. Does the recommendation agree with the patient information?")
    st.write("3. What additional information would you check before deciding?")
    if case_name.startswith("Case B"):
        st.error("Verification cue: this scenario contains a deliberately incorrect AI recommendation. Do not accept it without checking the case.")
    else:
        st.success("Compare the recommendation with the case details before deciding.")

st.divider()
st.subheader("4. Clinician decision")
st.write("This interaction records a simulated decision for the prototype evaluation.")
decision = st.radio("Your decision", ["Accept recommendation", "Reject recommendation", "Override / request further review"], horizontal=True, key=f"decision_{case_name}_{explanation_mode}")
reason = st.text_area("Brief reason for your decision (optional)", key=f"reason_{case_name}_{explanation_mode}")
if st.button("Record decision", type="primary"):
    record = {
        "timestamp": datetime.now(timezone.utc).isoformat(timespec="seconds"),
        "case": case_name,
        "modality": explanation_mode,
        "AI_recommendation": case["model_label"],
        "decision": decision,
        "reason": reason
    }
    st.session_state.events.append(record)
    st.success("Decision recorded in this session.")

with st.expander("Session decision log"):
    if st.session_state.events:
        st.dataframe(pd.DataFrame(st.session_state.events), width="stretch")
        st.download_button("Download session log (CSV)", pd.DataFrame(st.session_state.events).to_csv(index=False), "clinexplain_decisions.csv", "text/csv")
    else:
        st.caption("No decisions recorded yet.")

with st.expander("Prototype scope and limitations"):
    st.markdown("""
    - **Implemented:** synthetic case selection, two explanation views, accept/reject/override controls and session decision logging.
    - **Simulated:** AI recommendation, confidence and feature-contribution values.
    - **Not implemented:** trained clinical prediction model, real patient data, SHAP computation, validated counterfactual engine, clinician study or clinical validation.
    - **Evaluation status:** the interface supports walkthroughs and formative inspection. It does not establish that either explanation improves clinical performance.
    """)
